"""Generate tables.py from a Hermes source tree.

The opcode numbering of bytecode version 98 changed several times without a
version bump. The shipped tables.py is generated from the last v98 commit
(639e5d6af, the parent of "Bump bytecode version to 99"). To support a
different v98 snapshot, regenerate the tables from that checkout:

    python3 gen_tables.py /path/to/hermes-checkout > tables.py
"""

import os
import re
import sys

OPERAND_SIZES = {
    "Reg8": 1,
    "Reg32": 4,
    "UInt8": 1,
    "UInt16": 2,
    "UInt32": 4,
    "Addr8": 1,
    "Addr32": 4,
    "Imm32": 4,
    "Double": 8,
}


def strip_preprocessor(text):
    """Remove comments and preprocessor directives (with continuations)."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    out = []
    in_directive = False
    for line in text.splitlines():
        stripped = line.strip()
        if in_directive or stripped.startswith("#"):
            in_directive = stripped.endswith("\\")
            continue
        out.append(re.sub(r"//.*", "", line))
    return "\n".join(out)


def parse_bytecode_list(path):
    text = strip_preprocessor(open(path).read())
    opcodes = []
    string_ops = {}
    func_ops = {}
    bigint_ops = {}
    jump_long = {}
    ret_targets = set()
    for m in re.finditer(r"\b([A-Z_0-9]+)\s*\(([^()]*)\)", text):
        macro, args = m.group(1), [a.strip() for a in m.group(2).split(",")]
        if macro.startswith("DEFINE_OPCODE_"):
            opcodes.append((args[0], args[1:]))
        elif re.fullmatch(r"DEFINE_JUMP_\d", macro):
            n = int(macro[-1])
            short = ["Addr8"] + ["Reg8"] * (n - 1)
            long = ["Addr32"] + ["Reg8"] * (n - 1)
            opcodes.append((args[0], short))
            opcodes.append((args[0] + "Long", long))
            jump_long[args[0]] = args[0] + "Long"
        elif macro == "DEFINE_JUMP_LONG_VARIANT":
            jump_long[args[0]] = args[1]
        elif macro == "DEFINE_RET_TARGET":
            ret_targets.add(args[0])
        elif macro == "OPERAND_STRING_ID":
            string_ops.setdefault(args[0], []).append(int(args[1]))
        elif macro == "OPERAND_FUNCTION_ID":
            func_ops.setdefault(args[0], []).append(int(args[1]))
        elif macro == "OPERAND_BIGINT_ID":
            bigint_ops.setdefault(args[0], []).append(int(args[1]))
    return opcodes, string_ops, func_ops, bigint_ops, jump_long, ret_targets


def parse_builtins(path):
    text = strip_preprocessor(open(path).read())
    names = []
    for m in re.finditer(r"\b([A-Z_]+)\s*\(([^()]*)\)", text):
        macro, args = m.group(1), [a.strip() for a in m.group(2).split(",")]
        if macro in ("NORMAL_METHOD", "BUILTIN_METHOD"):
            names.append(("method", args[0], args[1]))
        elif macro in ("PRIVATE_BUILTIN", "JS_BUILTIN"):
            names.append(("private", "HermesBuiltin", args[0]))
    return names


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "."
    bc_list = os.path.join(root, "include/hermes/BCGen/HBC/BytecodeList.def")
    builtins = os.path.join(root, "include/hermes/FrontEndDefs/Builtins.def")
    version_h = os.path.join(root, "include/hermes/BCGen/HBC/BytecodeVersion.h")
    version = int(
        re.search(r"BYTECODE_VERSION\s*=\s*(\d+)", open(version_h).read()).group(1)
    )
    opcodes, string_ops, func_ops, bigint_ops, jump_long, ret_targets = (
        parse_bytecode_list(bc_list)
    )
    print("# @" + "generated by gen_tables.py. Do not edit by hand.")
    print("# Copyright (c) Meta Platforms, Inc. and affiliates.")
    print("#")
    print("# This source code is licensed under the MIT license found in the")
    print("# LICENSE file in the root directory of this source tree.")
    print()
    print("BYTECODE_VERSION = %d" % version)
    print()
    print("# (name, [operand types]) indexed by opcode number.")
    print("OPCODES = [")
    for name, ops in opcodes:
        print("    (%r, %r)," % (name, ops))
    print("]")
    print()
    print("# Opcode name -> 1-based operand indices that are string table IDs.")
    print("STRING_OPERANDS = %r" % dict(sorted(string_ops.items())))
    print("FUNCTION_OPERANDS = %r" % dict(sorted(func_ops.items())))
    print("BIGINT_OPERANDS = %r" % dict(sorted(bigint_ops.items())))
    print("JUMP_LONG_VARIANTS = %r" % dict(sorted(jump_long.items())))
    print("RET_TARGETS = %r" % sorted(ret_targets))
    print()
    print("# Builtin method names indexed by builtin number.")
    print("BUILTINS = [")
    for kind, obj, name in parse_builtins(builtins):
        print("    %r," % ("%s.%s" % (obj, name)))
    print("]")
    print()
    print("OPERAND_SIZES = %r" % OPERAND_SIZES)


if __name__ == "__main__":
    main()
